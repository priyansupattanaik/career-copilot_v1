def test_validate_jpeg_avatar():
    mime = validate_avatar_upload("photo.jpg", "image/jpeg", JPEG, 3 * 1024 * 1024)
    assert mime == "image/jpeg"


def test_validate_png_avatar():
    mime = validate_avatar_upload("photo.png", "image/png", PNG, 3 * 1024 * 1024)
    assert mime == "image/png"


def test_reject_oversize_avatar():
    content = b"\xff\xd8\xff" + b"0" * (3 * 1024 * 1024)
    with pytest.raises(ApiError) as raised:
        validate_avatar_upload("big.jpg", "image/jpeg", content, 3 * 1024 * 1024)
    assert raised.value.code == "avatar_too_large"


def test_reject_non_image():
    with pytest.raises(ApiError) as raised:
        validate_avatar_upload("file.txt", "text/plain", b"hello", 3 * 1024 * 1024)
    assert raised.value.code == "unsupported_avatar_type"
